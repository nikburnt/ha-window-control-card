async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("http://127.0.0.1:8768/preview/");
  await page.getByRole("heading", { name: "Wide Window" }).waitFor();
  await page.setViewportSize({ width: 1100, height: 850 });
  const before = await page.locator(".shade").first().evaluate((node) => node.getBoundingClientRect().height);
  await page.getByRole("button", { name: "Up: All", exact: true }).click();
  await page.waitForTimeout(1000);
  const after = await page.locator(".shade").first().evaluate((node) => node.getBoundingClientRect().height);
  check(after < before, "Window drawing did not follow changing positions");
  await page.getByRole("button", { name: "Stop: All", exact: true }).click();
  let calls = await page.evaluate(() => window.demo.calls);
  check(calls[0].type === "visual_logic/run" && calls[0].blueprintId === "demo-window-all" && calls[0].entryId === "start:up", "Whole-window command bypassed the server blueprint");
  check(calls[1].blueprintId === "demo-window-all" && calls[1].entryId === "start:stop", "Whole-window stop used wrong target");
  await page.getByRole("button", { name: "Roller Shades", exact: true }).click();
  await page.getByRole("button", { name: "Down: Roller Shades", exact: true }).click();
  calls = await page.evaluate(() => window.demo.calls);
  check(calls.at(-1).blueprintId === "demo-window-rollers" && calls.at(-1).entryId === "start:down", "Roller-only command used the wrong blueprint");
  await page.getByRole("button", { name: "Stop: Roller Shades", exact: true }).click();
  await page.getByRole("button", { name: "Open: Right Roller", exact: true }).click();
  calls = await page.evaluate(() => window.demo.calls);
  check(calls.at(-1).entity_id === "cover.window_right" && calls.at(-1).service === "set_cover_position" && calls.at(-1).position === 100, "Individual Open did not send 100 percent");
  await page.getByRole("button", { name: "Close: Right Roller", exact: true }).click();
  calls = await page.evaluate(() => window.demo.calls);
  check(calls.at(-1).service === "set_cover_position" && calls.at(-1).position === 0, "Individual Close did not send zero percent");
  await page.getByRole("button", { name: "Stop: Right Roller", exact: true }).click();
  calls = await page.evaluate(() => window.demo.calls);
  check(calls.at(-1).service === "stop_cover" && calls.at(-1).position === undefined, "Stop was converted into a position command");
  const slider = page.getByRole("slider", { name: "Opening: Right Roller", exact: true });
  const count = await page.evaluate(() => window.demo.calls.length);
  await slider.evaluate((node) => {
    for (const value of [20, 40, 60]) { node.value = value; node.dispatchEvent(new Event("input", { bubbles: true })); }
  });
  check(await page.evaluate(() => window.demo.calls.length) === count, "Slider sent commands before release");
  await slider.evaluate((node) => { node.value = "60"; node.dispatchEvent(new Event("change", { bubbles: true })); });
  calls = await page.evaluate(() => window.demo.calls);
  check(calls.length === count + 1 && calls.at(-1).position === 60, "Slider did not emit exactly one final position");
  await page.getByRole("button", { name: "Stop: Right Roller", exact: true }).click();
  await page.evaluate(() => window.demo.setUnavailable("cover.window_center"));
  check(await page.getByRole("button", { name: "Open: Center Roller", exact: true }).isDisabled(), "Unavailable member enabled");
  check(await page.getByRole("button", { name: "Open: Left Roller", exact: true }).isEnabled(), "Healthy member blocked by offline peer");
  await page.evaluate(() => window.demo.setUnknown("cover.window_left"));
  check(await page.getByRole("slider", { name: "Opening: Left Roller", exact: true }).getAttribute("aria-valuetext") === "Unknown", "Unknown reported as numeric zero");
  await page.evaluate(() => { window.demo.failNext = true; });
  await page.getByRole("button", { name: "Open: Curtain", exact: true }).click();
  check((await page.getByRole("alert").textContent()).includes("Command failed"), "Service failure was swallowed");
  await page.evaluate(() => { window.demo.rejectNext = true; });
  await page.getByRole("button", { name: "Down: Roller Shades", exact: true }).click();
  check((await page.getByRole("alert").textContent()).includes("Group is disabled"), "Rejected blueprint admission appeared successful");
  await page.goto("http://127.0.0.1:8768/preview/");
  await page.getByRole("heading", { name: "Wide Window" }).waitFor();
  await page.evaluate(() => window.demo.setLegacy());
  await page.getByRole("button", { name: "Open: All", exact: true }).click();
  await page.getByRole("button", { name: "Stop: All", exact: true }).click();
  await page.getByRole("button", { name: "Roller Shades", exact: true }).click();
  await page.getByRole("button", { name: "Close: Roller Shades", exact: true }).click();
  calls = await page.evaluate(() => window.demo.calls);
  check(calls[0].entity_id === "button.window_open_all" && calls[1].entity_id === "button.window_stop_all", "Legacy whole-window controls regressed");
  check(calls.at(-1).service === "set_cover_position" && calls.at(-1).position === 0 && calls.at(-1).entity_id === "cover.window_rollers", "Legacy roller group did not use position zero");
  await page.getByRole("button", { name: "Stop: Roller Shades", exact: true }).click();
  await page.goto("http://127.0.0.1:8768/preview/");
  await page.getByRole("heading", { name: "Wide Window" }).waitFor();
  await page.evaluate(() => window.demo.setEstimate("cover.window_right", 2));
  const eta = page.locator(".roller").nth(2).locator(".estimate");
  check((await eta.textContent()).includes("s left"), "No remaining-time estimate");
  const reported = await page.locator(".shade").nth(2).getAttribute("style");
  await page.waitForTimeout(2300);
  check(await eta.textContent() === "Awaiting Position", "Expired estimate claimed success or disappeared");
  check(await page.locator(".shade").nth(2).getAttribute("style") === reported, "Countdown fabricated motor progress");
  check(await page.evaluate(() => !document.querySelector("window-control-card")._ticker), "Expired countdown leaked its timer");
  await page.evaluate(() => window.demo.setEstimate("cover.window_right", 40, "pending"));
  check(await eta.textContent() === "", "Pending command started countdown before dispatch");
  await page.evaluate(() => window.demo.setEstimate("cover.window_right", 40));
  await page.getByRole("button", { name: "Stop: Right Roller", exact: true }).click();
  check(await eta.textContent() === "", "Stop left stale countdown visible");
  await page.evaluate(() => window.demo.setEstimate("cover.window_right", 40));
  await page.evaluate(() => window.demo.setError("cover.window_right"));
  check(await eta.textContent() === "", "Failure left stale countdown visible");
  await page.evaluate(() => {
    window.demo.setEstimate("cover.window_right", 40);
    const card = document.querySelector("window-control-card");
    const parent = card.parentElement;
    card.remove();
    if (card._ticker) throw new Error("Detached card leaked its timer");
    parent.append(card);
  });
  check(await page.evaluate(() => !!document.querySelector("window-control-card")._ticker), "Reconnected card did not resume countdown");
  await page.screenshot({ path: "output/playwright/desktop.png" });
  for (const width of [320, 390, 768]) {
    await page.setViewportSize({ width, height: 850 });
    await page.evaluate(() => window.demo.setLanguage("ru"));
    await page.evaluate(() => { window.demo.setEstimate("cover.window_left", 33); window.demo.setEstimate("cover.window_right", -1); });
    const overflow = await page.evaluate(() => {
      const card = document.querySelector("window-control-card");
      const bounds = card.getBoundingClientRect();
      const nodes = [...card.shadowRoot.querySelectorAll("button,input,.member-name,.status,.estimate,h2")];
      return nodes.filter((node) => { const r = node.getBoundingClientRect(); return r.left < bounds.left - 1 || r.right > bounds.right + 1; }).map((node) => node.outerHTML);
    });
    check(!overflow.length, `Horizontal overflow at ${width}: ${overflow.join("\n")}`);
    await page.screenshot({ path: `output/playwright/mobile-${width}.png` });
  }
  await page.setViewportSize({ width: 390, height: 850 });
  await page.evaluate(() => { window.demo.setDark(); window.demo.setUnavailable("cover.window_center"); window.demo.setError("cover.window_right"); });
  await page.screenshot({ path: "output/playwright/dark-errors.png" });
  await page.goto("http://127.0.0.1:8768/preview/?curtain_opening=right-to-left&position_display=closed");
  await page.getByRole("heading", { name: "Wide Window" }).waitFor();
  const closedSlider = page.getByRole("slider", { name: "Closure: Right Roller", exact: true });
  check(await closedSlider.inputValue() === "85", "15 percent open was not shown as 85 percent closed");
  await closedSlider.evaluate((node) => { node.value = "60"; node.dispatchEvent(new Event("input", { bubbles: true })); });
  check(await page.evaluate(() => window.demo.calls.length) === 0, "Closure slider sent a command before release");
  await closedSlider.evaluate((node) => node.dispatchEvent(new Event("change", { bubbles: true })));
  calls = await page.evaluate(() => window.demo.calls);
  check(calls.length === 1 && calls[0].service === "set_cover_position" && calls[0].position === 40, "60 percent closed did not send native position 40 exactly once");
  check(!errors.length, `Browser errors: ${errors.join("; ")}`);
  console.log("PASS: native/legacy groups, percentage Open/Close, closure slider conversion/release, separate Stop, rejected admission, reported positions, countdown/lifecycle, unavailable/unknown/errors and RU/mobile layouts; no browser errors or physical devices");
}
